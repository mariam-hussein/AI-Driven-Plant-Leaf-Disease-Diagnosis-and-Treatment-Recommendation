def load_leaf_segmentation_model(model_path):
    model = RFDETRSegNano(
        pretrain_weights=model_path,
        device=DEVICE,
        num_classes=1
    )
    model.optimize_for_inference(compile=False)
    return model


def load_classification_model(ckpt_path):
    """
    نحتاج فقط الـ emb
    ولا نحتاج classifier
    """
    checkpoint = torch.load(ckpt_path, map_location=DEVICE)

    weights = EfficientNet_B0_Weights.DEFAULT
    img_size = 224

    model = EffB0_SwinTiny_Fusion(
        num_classes=1,
        eff_weights=weights
    ).to(DEVICE)

    if isinstance(checkpoint, dict) and "model_state_dict" in checkpoint:
        state_dict = checkpoint["model_state_dict"]
        img_size = checkpoint.get("img_size", 224)
    else:
        state_dict = checkpoint

    filtered_state_dict = {}
    for k, v in state_dict.items():
        if not k.startswith("classifier."):
            filtered_state_dict[k] = v

    load_result = model.load_state_dict(filtered_state_dict, strict=False)

    print("[Classification] Model loaded for feature extraction.")
    print("[Classification] classifier layer ignored.")
    print("[Classification] Missing keys:", load_result.missing_keys)
    print("[Classification] Unexpected keys:", load_result.unexpected_keys)

    model.eval()

    eval_tf = transforms.Compose([
        transforms.Resize((img_size, img_size)),
        transforms.ToTensor(),
        transforms.Normalize(
            mean=weights.transforms().mean,
            std=weights.transforms().std
        ),
    ])

    return model, eval_tf, img_size


