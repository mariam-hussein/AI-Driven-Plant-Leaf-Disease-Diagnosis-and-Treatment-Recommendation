def build_prototypes_per_plant():
    print(f"Using device: {DEVICE}")

    print("Loading leaf segmentation model...")
    seg_model = load_leaf_segmentation_model(LEAF_SEG_MODEL_PATH)

    print("Loading classification model...")
    cls_model, cls_tf, img_size = load_classification_model(CLS_MODEL_PATH)

    print(f"Classification input size: {img_size}")

    folders = [
        d for d in os.listdir(HEALTHY_ROOT)
        if os.path.isdir(os.path.join(HEALTHY_ROOT, d))
    ]
    folders = sorted(folders)

    summary = {}
    last_result = {}
    all_failed = []

    for folder in folders:
        folder_path = os.path.join(HEALTHY_ROOT, folder)

        # اسم النبات فقط بدون healthy
        plant_name = clean_plant_name(folder)
        plant_name_safe = safe_name(plant_name)

        all_features, prototype, failed_images = process_single_plant_folder(
            folder_path=folder_path,
            plant_name=plant_name,
            seg_model=seg_model,
            cls_model=cls_model,
            cls_tf=cls_tf
        )

        all_failed.extend(failed_images)

        if all_features is None:
            print(f"[WARNING] No valid segmented healthy images for {plant_name}")

            summary[plant_name] = {
                "total_valid_features": 0,
                "feature_dim": 0,
                "all_features_file": None,
                "prototype_file": None,
                "prototype_saved": False,
                "failed_images": len(failed_images)
            }
            continue

        features_filename = f"{plant_name_safe}_all_features.npy"
        prototype_filename = f"{plant_name_safe}_prototype.npy"

        features_path = os.path.join(SAVE_DIR, features_filename)
        prototype_path = os.path.join(SAVE_DIR, prototype_filename)

        np.save(features_path, all_features)
        np.save(prototype_path, prototype)

        print(f"Saved features : {features_path} | shape={all_features.shape}")
        print(f"Saved prototype: {prototype_path} | shape={prototype.shape}")

        summary[plant_name] = {
            "total_valid_features": int(all_features.shape[0]),
            "feature_dim": int(all_features.shape[1]),
            "all_features_file": features_filename,
            "prototype_file": prototype_filename,
            "prototype_saved": True,
            "failed_images": len(failed_images)
        }

        last_result = {
            "plant_name": plant_name,
            "all_features_shape": list(all_features.shape),
            "prototype_shape": list(prototype.shape),
            "all_features_file": features_filename,
            "prototype_file": prototype_filename
        }

    summary_path = os.path.join(SAVE_DIR, "prototype_summary.json")
    last_result_path = os.path.join(SAVE_DIR, "last_prototype_inference_result.json")
    failed_path = os.path.join(SAVE_DIR, "failed_images.json")

    with open(summary_path, "w", encoding="utf-8") as f:
        json.dump(summary, f, ensure_ascii=False, indent=2)

    with open(last_result_path, "w", encoding="utf-8") as f:
        json.dump(last_result, f, ensure_ascii=False, indent=2)

    with open(failed_path, "w", encoding="utf-8") as f:
        json.dump(all_failed, f, ensure_ascii=False, indent=2)

    print("\n======================================")
    print("DONE")
    print(f"All outputs saved in: {SAVE_DIR}")
    print("======================================")


# =========================================================
# 9) RUN
# =========================================================
if __name__ == "__main__":
    build_prototypes_per_plant()