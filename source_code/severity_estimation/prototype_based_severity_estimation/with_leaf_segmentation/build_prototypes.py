def is_image_file(filename):
    return filename.lower().endswith(
        (".jpg", ".jpeg", ".png", ".bmp", ".tif", ".tiff", ".webp")
    )

def clean_plant_name(folder_name: str) -> str:
    """
    Apple___healthy -> Apple
    Corn_(maize)___healthy -> Corn_(maize)
    """
    name = folder_name.strip()
    name = re.sub(r'___healthy$', '', name, flags=re.IGNORECASE)
    name = re.sub(r'_healthy$', '', name, flags=re.IGNORECASE)
    name = re.sub(r'\s+healthy$', '', name, flags=re.IGNORECASE)
    return name.strip()

def safe_name(name: str) -> str:
    name = name.strip()
    name = name.replace("/", "_")
    name = name.replace("\\", "_")
    return name

def l2_normalize(vec, eps=1e-12):
    norm = np.linalg.norm(vec)
    if norm < eps:
        return vec
    return vec / norm

def get_bbox_from_mask(mask_bool):
    ys, xs = np.where(mask_bool)
    if len(xs) == 0 or len(ys) == 0:
        return None
    x1, x2 = xs.min(), xs.max()
    y1, y2 = ys.min(), ys.max()
    return x1, y1, x2, y2

def apply_mask_black_background(img_np, mask_bool):
    out = np.zeros_like(img_np)
    out[mask_bool] = img_np[mask_bool]
    return out

def crop_to_mask_bbox(img_np, mask_bool):
    bbox = get_bbox_from_mask(mask_bool)
    if bbox is None:
        return img_np
    x1, y1, x2, y2 = bbox
    return img_np[y1:y2+1, x1:x2+1]


