@torch.no_grad()
def extract_embedding(cls_model, transform, image_pil):
    x = transform(image_pil).unsqueeze(0).to(DEVICE)
    _, emb = cls_model(x)
    emb = emb.squeeze(0).detach().cpu().numpy().astype(np.float32)
    return emb


