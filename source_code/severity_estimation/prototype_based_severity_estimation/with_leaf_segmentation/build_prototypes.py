# 7) PROCESS ONE PLANT ONLY
# =========================================================
def process_single_plant_folder(folder_path, plant_name, seg_model, cls_model, cls_tf):
    image_files = [f for f in os.listdir(folder_path) if is_image_file(f)]
    image_files = sorted(image_files)

    all_features = []
    failed_images = []

    print(f"\nProcessing plant: {plant_name}")
    print(f"Total healthy images found: {len(image_files)}")

    for idx, fname in enumerate(image_files, start=1):
        if idx % 50 == 0 or idx == 1:
            print(f"[{plant_name}] Processing {idx}/{len(image_files)}")

        img_path = os.path.join(folder_path, fname)

        try:
            img_pil = Image.open(img_path).convert("RGB")

            # 1) segmentation first
            segmented_pil, seg_success = segment_leaf(seg_model, img_pil)

            # إذا فشل segmentation نتجاوز الصورة
            if not seg_success:
                failed_images.append({
                    "image": img_path,
                    "reason": "segmentation_failed"
                })
                continue

            # 2) extract embedding لهذه الصورة فقط
            emb = extract_embedding(cls_model, cls_tf, segmented_pil)

            if NORMALIZE_EACH_FEATURE:
                emb = l2_normalize(emb).astype(np.float32)

            # 3) نخزن feature الخاصة بهذا النبات فقط
            all_features.append(emb)

        except Exception as e:
            failed_images.append({
                "image": img_path,
                "reason": str(e)
            })

    if len(all_features) == 0:
        return None, None, failed_images

    # features الخاصة بهذا النبات فقط
    all_features = np.stack(all_features, axis=0).astype(np.float32)

    # prototype لهذا النبات فقط
    prototype = all_features.mean(axis=0).astype(np.float32)

    if NORMALIZE_FINAL_PROTOTYPE:
        prototype = l2_normalize(prototype).astype(np.float32)

    return all_features, prototype, failed_images


