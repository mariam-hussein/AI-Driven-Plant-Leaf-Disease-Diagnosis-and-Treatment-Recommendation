# 5) SEGMENT LEAF
# =========================================================
def segment_leaf(seg_model, image_pil):
    img_np = np.array(image_pil.convert("RGB"))

    detections = seg_model.predict(
        image_pil,
        threshold=SEG_THRESHOLD,
        iou_threshold=SEG_IOU_THRESHOLD
    )

    mask_combined = np.zeros(img_np.shape[:2], dtype=bool)

    if detections.mask is not None and len(detections.mask) > 0:
        for i in range(len(detections.mask)):
            mask_combined = np.logical_or(mask_combined, detections.mask[i])

    if not mask_combined.any():
        return None, False

    masked_np = apply_mask_black_background(img_np, mask_combined)

    if USE_BBOX_CROP:
        masked_np = crop_to_mask_bbox(masked_np, mask_combined)

    segmented_pil = Image.fromarray(masked_np.astype(np.uint8))
    return segmented_pil, True


